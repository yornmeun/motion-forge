<?php

namespace App\Services\Production;

use App\Enums\ProductionStatus;
use App\Models\Project;
use App\Models\RenderArtifact;
use App\Models\Scene;
use App\Models\SceneVersion;
use App\Models\User;
use App\Services\Production\Data\PlanResult;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use RuntimeException;

/** Applies storyboards to scenes, keeps versions, and guards locked narration on every edit. */
class StoryboardService
{
    public function __construct(private NarrationMatcher $matcher, private SrtParser $srt) {}

    public function apply(Project $project, PlanResult $plan, ?User $user): int
    {
        return DB::transaction(function () use ($project, $plan, $user) {
            $version = (int) $project->artifacts()->where('type', 'storyboard')->count() + 1;
            $rel = $project->storageDir("storyboards/storyboard-v{$version}.json");
            Storage::disk(config('motionforge.disk'))->put($rel, json_encode(['origin' => $plan->origin, 'meta' => $plan->meta, 'scenes' => $plan->scenes, 'created_at' => now()->toIso8601String()], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));
            RenderArtifact::create(['project_id' => $project->id, 'type' => 'storyboard', 'path' => $rel, 'size' => Storage::disk(config('motionforge.disk'))->size($rel), 'metadata' => ['version' => $version, 'origin' => $plan->origin, 'scenes' => count($plan->scenes), 'ai_request_id' => $plan->aiRequestId]]);

            $project->scenes()->delete();
            foreach ($plan->scenes as $i => $s) {
                $scene = Scene::create([
                    'project_id' => $project->id, 'sequence' => $i + 1, 'start_time' => $s['start_time'], 'end_time' => $s['end_time'],
                    'cue_start' => $s['cue_start'], 'cue_end' => $s['cue_end'], 'narration_reference' => $s['narration_reference'],
                    'kind' => $s['kind'], 'source' => $project->production_mode->value === 'native_video' ? 'ai_video' : 'canvas', 'status' => 'planned',
                ]);
                $v = SceneVersion::create(['scene_id' => $scene->id, 'version' => 1, 'plan' => $s, 'origin' => str_starts_with($plan->origin, 'ai') ? 'ai' : 'template', 'ai_request_id' => $plan->aiRequestId, 'created_by' => $user?->id, 'notes' => "Storyboard v{$version} ({$plan->origin})"]);
                $scene->update(['current_version_id' => $v->id]);
            }
            $project->update(['status' => ProductionStatus::Planned]);
            $project->log('storyboard.generated', "Storyboard v{$version} generated by {$plan->origin} with ".count($plan->scenes).' scenes.', ['warnings' => $plan->warnings], $user);

            return $version;
        });
    }

    /**
     * Create a new scene version from edits. Narration fields are rejected if they differ from the
     * locked SRT text. Returns the new version.
     */
    public function edit(Scene $scene, array $planChanges, ?string $code, User $user, string $origin = 'manual', ?string $notes = null): SceneVersion
    {
        $current = $scene->currentVersion;
        $plan = array_replace_recursive($current?->plan ?? [], $planChanges);
        $this->assertNarrationUnchanged($scene, $plan);
        $next = (int) $scene->versions()->max('version') + 1;
        $v = SceneVersion::create(['scene_id' => $scene->id, 'version' => $next, 'plan' => $plan, 'code' => $code ?? $current?->code, 'code_validation' => $code === null ? $current?->code_validation : null, 'origin' => $origin, 'created_by' => $user->id, 'notes' => $notes]);
        $scene->update(['current_version_id' => $v->id, 'status' => $code === null && $current?->code ? $scene->status : 'planned']);

        return $v;
    }

    public function assertNarrationUnchanged(Scene $scene, array $plan): void
    {
        if ($scene->kind !== 'story') {
            return;
        }
        $locked = (string) $scene->narration_reference;
        $given = (string) ($plan['narration_reference'] ?? $locked);
        if ($this->matcher->words($given) !== $this->matcher->words($locked) || trim($given) !== trim($locked)) {
            throw new LockedNarrationException('Scene narration is locked to the approved SRT and cannot be edited.');
        }
    }

    /**
     * Move the boundary between scene $scene and the next scene to a different cue, keeping
     * timing derived from the SRT. Only cue boundaries are allowed, so narration stays intact.
     */
    public function moveBoundary(Scene $scene, int $newCueEnd, User $user): void
    {
        $project = $scene->project;
        $next = $project->scenes()->where('sequence', $scene->sequence + 1)->first();
        if (! $next || $next->kind !== 'story' || $scene->kind !== 'story') {
            throw new RuntimeException('Only the boundary between two story scenes can be moved.');
        }
        if ($newCueEnd < $scene->cue_start || $newCueEnd >= $next->cue_end) {
            throw new RuntimeException('Each scene must keep at least one subtitle cue.');
        }
        $cues = $this->srt->parse($project->approvedPackage->srt_text);
        DB::transaction(function () use ($scene, $next, $newCueEnd, $cues, $user) {
            $boundary = max($scene->start_time + 0.6, round($cues[$newCueEnd + 1]['start'] - StoryboardBuilder::LEAD, 3));
            $scene->update(['cue_end' => $newCueEnd, 'end_time' => $boundary, 'narration_reference' => implode(' ', array_column(array_slice($cues, $scene->cue_start, $newCueEnd - $scene->cue_start + 1), 'text'))]);
            $next->update(['cue_start' => $newCueEnd + 1, 'start_time' => $boundary, 'narration_reference' => implode(' ', array_column(array_slice($cues, $newCueEnd + 1, $next->cue_end - $newCueEnd), 'text'))]);
            foreach ([$scene->fresh(), $next->fresh()] as $s) {
                $this->edit($s, ['start_time' => $s->start_time, 'end_time' => $s->end_time, 'cue_start' => $s->cue_start, 'cue_end' => $s->cue_end, 'narration_reference' => $s->narration_reference], null, $user, 'manual', 'Timing adjusted');
            }
        });
    }

    /** Validate a proposed scene order: story scenes must keep narration order; the end card stays last. */
    public function validateOrder(Project $project, array $orderedIds): array
    {
        $scenes = $project->scenes()->get()->keyBy('id');
        $errors = [];
        if (count($orderedIds) !== $scenes->count() || array_diff($orderedIds, $scenes->keys()->all())) {
            return ['The order must include every scene exactly once.'];
        }
        $lastCue = -1;
        foreach ($orderedIds as $i => $id) {
            $s = $scenes[$id];
            if ($s->kind === 'end_card' && $i !== count($orderedIds) - 1) $errors[] = 'The end card must stay last.';
            if ($s->kind === 'story' && $s->cue_start !== null) {
                if ($s->cue_start < $lastCue) $errors[] = "Scene {$s->sequence} would play its narration out of the approved order.";
                $lastCue = $s->cue_end;
            }
        }

        return array_values(array_unique($errors));
    }
}
