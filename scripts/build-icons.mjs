// Generates resources/js/icons.generated.js with only the Lucide icons MotionForge uses, so the
// bundle no longer ships every icon. It scans Blade views and PHP for quoted kebab-case names that
// are real Lucide icons (this also catches names passed through component props or PHP arrays).
// Runs automatically before `npm run build` / `npm run dev`; re-run after adding an icon by hand.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { icons } from 'lucide';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const pascal = (kebab) => kebab.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const known = new Set(Object.keys(icons));

function* files(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) yield* files(p);
        else if (e.name.endsWith('.php')) yield p;
    }
}

const used = new Set(['Circle']); // fallback glyph
for (const dir of ['resources/views', 'app']) {
    for (const f of files(path.join(root, dir))) {
        const src = fs.readFileSync(f, 'utf8');
        for (const m of src.matchAll(/['"]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"]/g)) {
            const name = pascal(m[1]);
            if (known.has(name)) used.add(name);
        }
    }
}

const names = [...used].sort();
const out = `// Generated by scripts/build-icons.mjs. Do not edit; re-run \`npm run icons\`.\n`
    + `import { ${names.join(', ')} } from 'lucide';\n\n`
    + `export const icons = { ${names.join(', ')} };\n`;
fs.writeFileSync(path.join(root, 'resources/js/icons.generated.js'), out);
console.log(`icons.generated.js: ${names.length} of ${known.size} Lucide icons`);
